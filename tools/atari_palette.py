#!/usr/bin/env python3
"""The 256 colours atari800 shows for an NTSC Atari, with its default "standard" setup.

The editor and the PNG previews used to invent colours from a hue wheel, so a byte looked
different there than in the emulator. This is the emulator's own recipe (src/colours_ntsc.c
and the STANDARD preset in src/colours.c: gamma 2.35, black 16, white 235, colour delay
26.8 degrees, no extra saturation, contrast, brightness or tint). Run it to regenerate
web/atari-ntsc.js:

    python3 tools/atari_palette.py
"""

from __future__ import annotations

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# NTSC luma multipliers from CGIA.PDF, as atari800 uses them.
LUMA = [0.6941, 0.7091, 0.7241, 0.7401, 0.7560, 0.7741, 0.7931, 0.8121,
        0.8260, 0.8470, 0.8700, 0.8930, 0.9160, 0.9420, 0.9690, 1.0000]
COLOR_DELAY = 26.8  # degrees; chosen by atari800 to match the colour names in GTIA.PDF
GAMMA = 2.35
BLACK, WHITE = 16 / 255, 235 / 255


def _gamma_to_linear(c: float) -> float:
    return c ** GAMMA if c >= 0 else c / 12.92


def _linear_to_srgb(c: float) -> float:
    return c * 12.92 if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def ntsc_rgb() -> list[tuple[int, int, int]]:
    """RGB for colour bytes 0..255, in order, as atari800's standard NTSC palette."""
    burst = 303.0 * math.pi / 180  # the colourburst angle in YIQ
    step = COLOR_DELAY * math.pi / 180
    out = []
    for hue in range(16):
        angle = burst + (hue - 1) * step
        sat = 0.175 if hue else 0.0
        i, q = math.cos(angle) * sat, math.sin(angle) * sat
        for lum in range(16):
            y = (LUMA[lum] - LUMA[0]) / (LUMA[15] - LUMA[0])
            y = y * (WHITE - BLACK) + BLACK
            r = _linear_to_srgb(_gamma_to_linear(y + 0.9563 * i + 0.6210 * q))
            g = _linear_to_srgb(_gamma_to_linear(y - 0.2721 * i - 0.6474 * q))
            b = _linear_to_srgb(_gamma_to_linear(y - 1.1070 * i + 1.7046 * q))
            out.append(tuple(max(0, min(255, round(c * 255))) for c in (r, g, b)))
    return out


def atari_rgb(byte: int) -> tuple[int, int, int]:
    return ntsc_rgb()[byte & 255]


def write_js(path: Path | None = None) -> None:
    """web/atari-ntsc.js: the same 256 colours, for the editor."""
    path = path or ROOT / "web" / "atari-ntsc.js"
    colours = ",\n  ".join(f'"#{r:02x}{g:02x}{b:02x}"' for r, g, b in ntsc_rgb())
    path.write_text(
        "// The 256 NTSC colours atari800 shows with its default setup. Generated by tools/atari_palette.py;\n"
        "// do not edit by hand (regenerate with `python3 tools/atari_palette.py`).\n"
        "export const ATARI_NTSC = [\n  " + colours + ",\n];\n"
    )


if __name__ == "__main__":
    write_js()
    print(f"wrote {ROOT / 'web' / 'atari-ntsc.js'}")
